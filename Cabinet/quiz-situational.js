// Максимум баллов по каждой шкале — считается от реального количества
// вопросов этой шкалы в SITUATIONAL_QUESTIONS (а не задаётся вручную), чтобы
// пороги ниже автоматически оставались верными, даже если вопросы когда-то
// поменяются местами или количество на шкалу изменится.
const SITUATIONAL_SCALE_MAX = SITUATIONAL_SCALES.reduce((acc, s) => {
  acc[s.key] = SITUATIONAL_QUESTIONS.filter((q) => q.scale === s.key).length;
  return acc;
}, {});

// Тир по проценту от максимума данной шкалы (проверено на примере из PDF —
// см. шапку файла): <34% низкий, 34–66% средний, >66% высокий.
function situationalTier(score, max) {
  if (!max) return "medium";
  const pct = score / max;
  if (pct < 0.34) return "low";
  if (pct > 0.66) return "high";
  return "medium";
}

function situationalTierLabel(tier) {
  if (tier === "high") return "высокий";
  if (tier === "medium") return "средний";
  return "низкий";
}

const SITUATIONAL_STORAGE_KEY = "gembalab_situational_result_v1";

function saveSituationalResult(totals, aiData) {
  try {
    localStorage.setItem(
      SITUATIONAL_STORAGE_KEY,
      JSON.stringify({ totals: totals, ai: aiData || null, savedAt: Date.now() })
    );
  } catch (e) {}
}

function loadSituationalResult() {
  try {
    const raw = localStorage.getItem(SITUATIONAL_STORAGE_KEY);
    return raw ? JSON.parse(raw) : null;
  } catch (e) {
    return null;
  }
}

function clearSituationalResult() {
  try {
    localStorage.removeItem(SITUATIONAL_STORAGE_KEY);
  } catch (e) {}
}

// Общая отрисовка отчёта (график + расшифровка + рекомендации) — используется
// и на экране результатов внутри самого теста, и в разделе "Результаты"
// личного кабинета, и в админке. Если передан aiData — используется
// персональный текст ИИ вместо шаблонного.
function renderSituationalReport(els, totals, aiData) {
  const results = SITUATIONAL_SCALES.map((s) => {
    const max = SITUATIONAL_SCALE_MAX[s.key] || 1;
    const score = totals[s.key] || 0;
    return { ...s, score, max, tier: situationalTier(score, max) };
  });

  // график — высота столбика по проценту от максимума своей шкалы
  els.chartEl.innerHTML = "";
  results.forEach((r) => {
    const col = document.createElement("div");
    col.className = "cabinet__result-bar-col";

    const bar = document.createElement("div");
    bar.className = "cabinet__result-bar" + (r.tier === "high" ? " cabinet__result-bar--high" : "");
    const pct = Math.max(6, Math.round((r.score / r.max) * 100));
    bar.style.height = pct + "%";
    bar.textContent = r.score;

    const label = document.createElement("div");
    label.className = "cabinet__result-bar-label";
    label.textContent = r.label;

    col.appendChild(bar);
    col.appendChild(label);
    els.chartEl.appendChild(col);
  });

  // баллы
  els.scoresEl.innerHTML = "";
  results.forEach((r) => {
    const li = document.createElement("li");
    const tierSpan =
      '<span class="cabinet__result-tier' +
      (r.tier === "high" ? " cabinet__result-tier--high" : "") +
      '">' + situationalTierLabel(r.tier) + " уровень</span>";
    li.innerHTML = "<span>" + r.label + "</span><span>" + r.score + " из " + r.max + " баллов · " + tierSpan + "</span>";
    els.scoresEl.appendChild(li);
  });

  // расшифровка (текст ИИ, если есть, иначе шаблон)
  els.breakdownEl.innerHTML = "";
  results.forEach((r) => {
    const aiText = aiData && aiData.breakdown && aiData.breakdown[r.key];
    const item = document.createElement("div");
    item.className = "cabinet__result-item" + (aiText ? " cabinet__result-item--ai" : "");
    item.dataset.cat = r.key;
    const title = document.createElement("div");
    title.className = "cabinet__result-item-title";
    title.textContent = r.label + " (" + r.score + " из " + r.max + ")";
    const text = document.createElement("p");
    text.className = "cabinet__result-item-text";
    text.textContent = aiText || SITUATIONAL_SCALE_TEMPLATES[r.key][r.tier];
    item.appendChild(title);
    item.appendChild(text);
    els.breakdownEl.appendChild(item);
  });

  // рекомендации — начиная с самых слабых шкал
  const weak = results.filter((r) => r.tier !== "high").sort((a, b) => a.score / a.max - b.score / b.max);
  const strong = results.filter((r) => r.tier === "high");
  els.recommendEl.innerHTML = "";

  const intro = document.createElement("p");
  intro.className = "cabinet__result-item-text";
  intro.style.marginBottom = "18px";
  if (aiData && aiData.recommendations_intro) {
    intro.textContent = aiData.recommendations_intro;
  } else if (weak.length === 0) {
    intro.textContent = "Все пять шкал выражены хорошо — держите этот баланс и дальше.";
  } else if (strong.length === 0) {
    intro.textContent = "Ярко выраженной «сильной» шкалы пока нет — стоит равномерно подтягивать все направления ниже.";
  } else {
    intro.textContent =
      "Главное — сохранить вашу сильную сторону (" +
      strong.map((r) => r.label).join(", ") +
      "), при этом аккуратно развивать: " +
      weak.map((r) => r.label).join(", ") +
      ".";
  }
  els.recommendEl.appendChild(intro);

  weak.forEach((r) => {
    const group = document.createElement("div");
    group.className = "cabinet__result-recommend-group";
    const title = document.createElement("div");
    title.className = "cabinet__result-recommend-title";
    title.textContent = r.label;
    const ul = document.createElement("ul");
    SITUATIONAL_TIPS[r.key].forEach((tip) => {
      const li = document.createElement("li");
      li.textContent = tip;
      ul.appendChild(li);
    });
    group.appendChild(title);
    group.appendChild(ul);
    els.recommendEl.appendChild(group);
  });

  return results;
}

